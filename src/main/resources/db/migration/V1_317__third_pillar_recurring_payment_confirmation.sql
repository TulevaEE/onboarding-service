CREATE TABLE third_pillar_recurring_payment_confirmation
(
    id            bigint GENERATED BY DEFAULT AS IDENTITY,
    personal_code text        NOT NULL,
    confirmed_at  timestamptz NOT NULL,
    CONSTRAINT third_pillar_recurring_payment_confirmation_pkey PRIMARY KEY (id)
);

CREATE INDEX idx_third_pillar_recurring_confirmation_person_time
    ON third_pillar_recurring_payment_confirmation (personal_code, confirmed_at);
