-- The depot fee: who bears it (investment_fee_policy), where its rate comes from
-- (investment_fee_rate.rate_source), and when the real rate starts (2026-09-18).

-- charged_to_fund = false means the fee is accrued to record Tuleva's cost but kept out of the
-- fund's NAV and out of its ledger.
CREATE TABLE investment_fee_policy (
    id              bigint GENERATED BY DEFAULT AS IDENTITY,
    fund_code       text        NOT NULL,
    fee_type        text        NOT NULL,
    charged_to_fund boolean     NOT NULL,
    valid_from      date        NOT NULL,
    valid_to        date,
    created_at      timestamptz NOT NULL DEFAULT now(),
    created_by      text,

    CONSTRAINT investment_fee_policy_pkey PRIMARY KEY (id),
    CONSTRAINT investment_fee_policy_fund_code_fee_type_valid_from_key
        UNIQUE (fund_code, fee_type, valid_from),
    CONSTRAINT investment_fee_policy_valid_range_check
        CHECK (valid_to IS NULL OR valid_to >= valid_from)
);

CREATE INDEX investment_fee_policy_fund_code_fee_type_idx
    ON investment_fee_policy (fund_code, fee_type);

