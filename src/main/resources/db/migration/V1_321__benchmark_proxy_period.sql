CREATE TABLE benchmark_proxy_period (
    id           bigint GENERATED BY DEFAULT AS IDENTITY,
    holding_isin varchar(12) NOT NULL,
    proxy_isin   varchar(12) NOT NULL,
    valid_until  date        NOT NULL,
    created_at   timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT pk_benchmark_proxy_period PRIMARY KEY (id),
    CONSTRAINT uq_benchmark_proxy_period_holding_valid_until UNIQUE (holding_isin, valid_until),
    CONSTRAINT fk_benchmark_proxy_period_holding
        FOREIGN KEY (holding_isin) REFERENCES instrument_reference (isin),
    CONSTRAINT fk_benchmark_proxy_period_proxy
        FOREIGN KEY (proxy_isin) REFERENCES instrument_reference (isin)
);

CREATE INDEX idx_benchmark_proxy_period_proxy_isin ON benchmark_proxy_period (proxy_isin);

