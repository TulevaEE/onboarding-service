CREATE TABLE investment_kid_calculation (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY,
    fund_code               text           NOT NULL,
    calculation_month       date           NOT NULL,
    version                 int            NOT NULL,
    complete                boolean        NOT NULL,
    refusal_reasons         text,
    series_segments         text,
    last_price_date         date,
    ocf_publication_id      bigint,
    ocf_valid_from          date,
    ocf_snapshot_id         bigint,
    ocf_snapshot_month      date,
    ongoing_charges         numeric(10, 8),
    ocf_rate_source         text,
    transaction_cost_source text           NOT NULL,
    calculated_at           timestamptz    NOT NULL,

    CONSTRAINT investment_kid_calculation_pkey PRIMARY KEY (id),
    CONSTRAINT investment_kid_calculation_fund_month_version_key
        UNIQUE (fund_code, calculation_month, version),
    CONSTRAINT investment_kid_calculation_id_fund_month_key
        UNIQUE (id, fund_code, calculation_month),
    CONSTRAINT investment_kid_calculation_ocf_publication_fkey
        FOREIGN KEY (ocf_publication_id) REFERENCES investment_ocf_publication (id),
    CONSTRAINT investment_kid_calculation_ocf_snapshot_fkey
        FOREIGN KEY (ocf_snapshot_id) REFERENCES investment_ocf_snapshot (id),
    CONSTRAINT investment_kid_calculation_version_positive
        CHECK (version >= 1),
    CONSTRAINT investment_kid_calculation_month_starts_on_its_first_day
        CHECK (EXTRACT(DAY FROM calculation_month) = 1),
    CONSTRAINT investment_kid_calculation_refused_exactly_when_incomplete
        CHECK (complete = (refusal_reasons IS NULL)),
    CONSTRAINT investment_kid_calculation_complete_names_its_series_and_ocf
        CHECK (NOT complete
           OR (series_segments IS NOT NULL
               AND last_price_date IS NOT NULL
               AND ocf_publication_id IS NOT NULL)),
    CONSTRAINT investment_kid_calculation_ocf_publication_fields_together
        CHECK ((ocf_publication_id IS NULL) = (ocf_valid_from IS NULL)
           AND (ocf_publication_id IS NULL) = (ongoing_charges IS NULL)
           AND (ocf_publication_id IS NULL) = (ocf_rate_source IS NULL)),
    CONSTRAINT investment_kid_calculation_ocf_rate_source
        CHECK (ocf_rate_source IN ('CALCULATION_UNROUNDED', 'PUBLISHED_FIGURE')),
    CONSTRAINT investment_kid_calculation_ocf_rate_from_a_calculation_names_it
        CHECK (ocf_rate_source IS NULL
           OR (ocf_rate_source = 'CALCULATION_UNROUNDED') = (ocf_snapshot_id IS NOT NULL)),
    CONSTRAINT investment_kid_calculation_ocf_snapshot_fields_together
        CHECK ((ocf_snapshot_id IS NULL) = (ocf_snapshot_month IS NULL)),
    CONSTRAINT investment_kid_calculation_ocf_snapshot_only_with_its_publication
        CHECK (ocf_snapshot_id IS NULL OR ocf_publication_id IS NOT NULL),
    CONSTRAINT investment_kid_calculation_series_fields_together
        CHECK ((series_segments IS NULL) = (last_price_date IS NULL)),
    CONSTRAINT investment_kid_calculation_transaction_cost_source
        CHECK (transaction_cost_source IN ('PUBLISHED_OCF'))
);

CREATE INDEX idx_kid_calculation_ocf_publication
    ON investment_kid_calculation (ocf_publication_id);
CREATE INDEX idx_kid_calculation_ocf_snapshot
    ON investment_kid_calculation (ocf_snapshot_id);

CREATE TABLE investment_kid_scenario (
    id                                bigint GENERATED BY DEFAULT AS IDENTITY,
    calculation_id                    bigint         NOT NULL,
    horizon_years                     int            NOT NULL,
    kind                              text           NOT NULL,
    window_source                     text           NOT NULL,
    window_start                      date           NOT NULL,
    window_end                        date           NOT NULL,
    window_months                     int,
    unrounded_amount_eur              numeric(19, 8) NOT NULL,
    printed_amount_eur                numeric(19, 0) NOT NULL,
    unrounded_average_return_per_year numeric(12, 8) NOT NULL,
    printed_average_return_per_year   numeric(8, 4)  NOT NULL,

    CONSTRAINT investment_kid_scenario_pkey PRIMARY KEY (id),
    CONSTRAINT investment_kid_scenario_calculation_fkey
        FOREIGN KEY (calculation_id) REFERENCES investment_kid_calculation (id),
    CONSTRAINT investment_kid_scenario_calculation_horizon_kind_key
        UNIQUE (calculation_id, horizon_years, kind),
    CONSTRAINT investment_kid_scenario_horizon_positive
        CHECK (horizon_years >= 1),
    CONSTRAINT investment_kid_scenario_kind
        CHECK (kind IN ('STRESS', 'UNFAVOURABLE', 'MODERATE', 'FAVOURABLE')),
    CONSTRAINT investment_kid_scenario_window_source
        CHECK (window_source IN ('FULL_LENGTH', 'SHORTER', 'STRESSED_VOLATILITY')),
    CONSTRAINT investment_kid_scenario_month_windows_carry_their_length
        CHECK ((window_source = 'STRESSED_VOLATILITY') = (window_months IS NULL)),
    CONSTRAINT investment_kid_scenario_window_order
        CHECK (window_start <= window_end)
);

CREATE TABLE investment_kid_cost (
    id                                      bigint GENERATED BY DEFAULT AS IDENTITY,
    calculation_id                          bigint         NOT NULL,
    horizon_years                           int            NOT NULL,
    unrounded_total_costs_eur               numeric(19, 8) NOT NULL,
    printed_total_costs_eur                 numeric(19, 0) NOT NULL,
    unrounded_annual_cost_impact            numeric(12, 8) NOT NULL,
    printed_annual_cost_impact              numeric(8, 4)  NOT NULL,
    unrounded_return_per_year_before_costs  numeric(12, 8) NOT NULL,
    printed_return_per_year_before_costs    numeric(8, 4)  NOT NULL,
    unrounded_return_per_year_after_costs   numeric(12, 8) NOT NULL,
    printed_return_per_year_after_costs     numeric(8, 4)  NOT NULL,

    CONSTRAINT investment_kid_cost_pkey PRIMARY KEY (id),
    CONSTRAINT investment_kid_cost_calculation_fkey
        FOREIGN KEY (calculation_id) REFERENCES investment_kid_calculation (id),
    CONSTRAINT investment_kid_cost_calculation_horizon_key
        UNIQUE (calculation_id, horizon_years),
    CONSTRAINT investment_kid_cost_horizon_positive
        CHECK (horizon_years >= 1)
);

CREATE TABLE investment_kid_publication (
    id                bigint GENERATED BY DEFAULT AS IDENTITY,
    fund_code         text        NOT NULL,
    calculation_month date        NOT NULL,
    calculation_id    bigint      NOT NULL,
    published_by      text        NOT NULL,
    published_at      timestamptz NOT NULL,

    CONSTRAINT investment_kid_publication_pkey PRIMARY KEY (id),
    CONSTRAINT investment_kid_publication_fund_month_key UNIQUE (fund_code, calculation_month),
    CONSTRAINT investment_kid_publication_calculation_key UNIQUE (calculation_id),
    CONSTRAINT investment_kid_publication_calculation_of_the_month_fkey
        FOREIGN KEY (calculation_id, fund_code, calculation_month)
            REFERENCES investment_kid_calculation (id, fund_code, calculation_month)
);

