CREATE TABLE investment_provider_agreement (
    id         bigint GENERATED BY DEFAULT AS IDENTITY,
    created_at timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT pk_provider_agreement PRIMARY KEY (id)
);

CREATE TABLE investment_provider_agreement_version (
    id                    bigint GENERATED BY DEFAULT AS IDENTITY,
    provider_agreement_id bigint      NOT NULL,
    accrual_method        text        NOT NULL,
    payment_period        text        NOT NULL,
    payer_label           text        NOT NULL,
    valid_from            date        NOT NULL,
    valid_to              date,
    created_at            timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT pk_provider_agreement_version PRIMARY KEY (id),
    CONSTRAINT uq_provider_agreement_version_valid_from UNIQUE (provider_agreement_id, valid_from),
    CONSTRAINT fk_provider_agreement_version_agreement
        FOREIGN KEY (provider_agreement_id) REFERENCES investment_provider_agreement (id),
    CONSTRAINT chk_provider_agreement_version_accrual_method
        CHECK (accrual_method IN ('DAILY_HOLDING', 'MONTH_END_HOLDING', 'QUARTER_AVERAGE_MONTH_END')),
    CONSTRAINT chk_provider_agreement_version_payment_period
        CHECK (payment_period IN ('MONTH', 'QUARTER')),
    CONSTRAINT chk_provider_agreement_version_validity
        CHECK (valid_to IS NULL OR valid_to >= valid_from)
);

CREATE INDEX idx_provider_agreement_version_agreement
    ON investment_provider_agreement_version (provider_agreement_id);

ALTER TABLE investment_instrument_fee ADD COLUMN provider_agreement_id bigint;

ALTER TABLE investment_instrument_fee ADD CONSTRAINT fk_instrument_fee_provider_agreement
    FOREIGN KEY (provider_agreement_id) REFERENCES investment_provider_agreement (id);

CREATE INDEX idx_instrument_fee_provider_agreement
    ON investment_instrument_fee (provider_agreement_id);

CREATE TABLE investment_instrument_fee_accrual (
    id                            bigint GENERATED BY DEFAULT AS IDENTITY,
    fund_code                     text            NOT NULL,
    isin                          varchar(12)     NOT NULL,
    accrual_date                  date            NOT NULL,
    instrument_fee_id             bigint          NOT NULL,
    provider_agreement_version_id bigint          NOT NULL,
    accrual_method                text            NOT NULL,
    rate_status                   text            NOT NULL,
    instrument_fee_rate_id        bigint,
    rebate_rate                   numeric(10, 8)  NOT NULL,
    invoiced_fee_rate             numeric(10, 8)  NOT NULL,
    units                         numeric(24, 8)  NOT NULL,
    units_source                  text            NOT NULL,
    units_date                    date            NOT NULL,
    price                         numeric(24, 8)  NOT NULL,
    price_date                    date            NOT NULL,
    price_source                  text            NOT NULL,
    rebate_amount                 numeric(24, 10) NOT NULL,
    invoiced_fee_amount           numeric(24, 10) NOT NULL,
    calculated_at                 timestamptz     NOT NULL,

    CONSTRAINT pk_instrument_fee_accrual PRIMARY KEY (id),
    CONSTRAINT uq_instrument_fee_accrual_fund_isin_date UNIQUE (fund_code, isin, accrual_date),
    CONSTRAINT fk_instrument_fee_accrual_agreement
        FOREIGN KEY (instrument_fee_id) REFERENCES investment_instrument_fee (id),
    CONSTRAINT fk_instrument_fee_accrual_provider_agreement_version
        FOREIGN KEY (provider_agreement_version_id)
            REFERENCES investment_provider_agreement_version (id),
    CONSTRAINT fk_instrument_fee_accrual_rate
        FOREIGN KEY (instrument_fee_rate_id) REFERENCES investment_instrument_fee_rate (id),
    CONSTRAINT chk_instrument_fee_accrual_method
        CHECK (accrual_method IN ('DAILY_HOLDING', 'MONTH_END_HOLDING', 'QUARTER_AVERAGE_MONTH_END')),
    CONSTRAINT chk_instrument_fee_accrual_rate_status
        CHECK (rate_status IN ('RESOLVED', 'PROVISIONAL')),
    CONSTRAINT chk_instrument_fee_accrual_a_resolved_rate_names_its_row
        CHECK ((rate_status = 'RESOLVED') = (instrument_fee_rate_id IS NOT NULL)),
    CONSTRAINT chk_instrument_fee_accrual_units_source
        CHECK (units_source IN ('NAV_REPORT', 'SETTLED', 'NAV_REPORT_WITHOUT_SEB_REPORTS',
                                'NAV_REPORT_SEB_REPORTS_INCOMPLETE')),
    CONSTRAINT chk_instrument_fee_accrual_rebate_is_a_discount CHECK (rebate_rate >= 0),
    CONSTRAINT chk_instrument_fee_accrual_invoiced_is_a_charge CHECK (invoiced_fee_rate >= 0),
    CONSTRAINT chk_instrument_fee_accrual_holds_units CHECK (units > 0),
    CONSTRAINT chk_instrument_fee_accrual_has_a_price CHECK (price > 0),
    CONSTRAINT chk_instrument_fee_accrual_inputs_not_after_the_day
        CHECK (units_date <= accrual_date AND price_date <= accrual_date)
);

CREATE INDEX idx_instrument_fee_accrual_agreement
    ON investment_instrument_fee_accrual (instrument_fee_id);
CREATE INDEX idx_instrument_fee_accrual_provider_agreement_version
    ON investment_instrument_fee_accrual (provider_agreement_version_id);
CREATE INDEX idx_instrument_fee_accrual_rate
    ON investment_instrument_fee_accrual (instrument_fee_rate_id);
CREATE INDEX idx_instrument_fee_accrual_date
    ON investment_instrument_fee_accrual (accrual_date);
