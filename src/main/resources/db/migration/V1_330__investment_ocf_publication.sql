CREATE TABLE investment_ocf_publication (
    id                     bigint GENERATED BY DEFAULT AS IDENTITY,
    fund_code              text           NOT NULL,
    valid_from             date           NOT NULL,
    published_ocf          numeric(10, 8) NOT NULL,
    published_decimals     smallint       NOT NULL,
    basis                  text           NOT NULL,
    basis_reason           text           NOT NULL,
    snapshot_id            bigint,
    management_fee_rate    numeric(10, 8),
    management_fee_rate_id bigint,
    ex_post_period_start   date,
    ex_post_period_end     date,
    published_in           text           NOT NULL,
    published_by           text           NOT NULL,
    recorded_at            timestamptz    NOT NULL DEFAULT now(),

    CONSTRAINT investment_ocf_publication_pkey PRIMARY KEY (id),
    CONSTRAINT investment_ocf_publication_snapshot_fkey
        FOREIGN KEY (snapshot_id) REFERENCES investment_ocf_snapshot (id),
    CONSTRAINT investment_ocf_publication_fund_valid_from_published_in_key
        UNIQUE (fund_code, valid_from, published_in),
    CONSTRAINT investment_ocf_publication_published_decimals
        CHECK (published_decimals BETWEEN 1 AND 4),
    CONSTRAINT investment_ocf_publication_basis
        CHECK (basis IN ('MONTHLY_ESTIMATE', 'EX_POST')),
    CONSTRAINT investment_ocf_publication_calculation_carries_its_fee_rate
        CHECK ((snapshot_id IS NULL) = (management_fee_rate IS NULL)
           AND (snapshot_id IS NULL) = (management_fee_rate_id IS NULL)),
    CONSTRAINT investment_ocf_publication_ex_post_carries_its_period
        CHECK ((basis = 'EX_POST') = (ex_post_period_start IS NOT NULL)),
    CONSTRAINT investment_ocf_publication_ex_post_period_has_both_ends
        CHECK ((ex_post_period_start IS NULL) = (ex_post_period_end IS NULL)),
    CONSTRAINT investment_ocf_publication_ex_post_is_not_a_calculation
        CHECK (basis <> 'EX_POST' OR snapshot_id IS NULL),
    CONSTRAINT investment_ocf_publication_ex_post_period_order
        CHECK (ex_post_period_start <= ex_post_period_end)
);

CREATE INDEX idx_ocf_publication_snapshot ON investment_ocf_publication (snapshot_id);

CREATE TABLE investment_ocf_exception (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY,
    snapshot_id             bigint      NOT NULL,
    calculation_fingerprint text        NOT NULL,
    reason                  text        NOT NULL,
    decided_by              text        NOT NULL,
    decided_at              timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT investment_ocf_exception_pkey PRIMARY KEY (id),
    CONSTRAINT investment_ocf_exception_snapshot_fkey
        FOREIGN KEY (snapshot_id) REFERENCES investment_ocf_snapshot (id),
    CONSTRAINT investment_ocf_exception_snapshot_fingerprint_key
        UNIQUE (snapshot_id, calculation_fingerprint)
);

CREATE TABLE investment_ocf_kid_review (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY,
    fund_code               text           NOT NULL,
    publication_id          bigint         NOT NULL,
    snapshot_id             bigint         NOT NULL,
    calculation_fingerprint text           NOT NULL,
    reviewed_ocf            numeric(10, 8) NOT NULL,
    reason                  text           NOT NULL,
    reviewed_by             text           NOT NULL,
    reviewed_at             timestamptz    NOT NULL DEFAULT now(),

    CONSTRAINT investment_ocf_kid_review_pkey PRIMARY KEY (id),
    CONSTRAINT investment_ocf_kid_review_publication_fkey
        FOREIGN KEY (publication_id) REFERENCES investment_ocf_publication (id),
    CONSTRAINT investment_ocf_kid_review_snapshot_fkey
        FOREIGN KEY (snapshot_id) REFERENCES investment_ocf_snapshot (id)
);

CREATE INDEX idx_ocf_kid_review_publication ON investment_ocf_kid_review (publication_id);
CREATE INDEX idx_ocf_kid_review_snapshot ON investment_ocf_kid_review (snapshot_id);
