CREATE TABLE insurance_transfer_form
(
    id                     bigint GENERATED BY DEFAULT AS IDENTITY,
    user_id                bigint      NOT NULL,
    insurer                text        NOT NULL,
    pension_account_number text        NOT NULL,
    filled_pdf             bytea,
    signed_container       bytea,
    signed_at              timestamptz,
    email_status           text,
    created_at             timestamptz NOT NULL,
    CONSTRAINT insurance_transfer_form_pkey PRIMARY KEY (id),
    CONSTRAINT fk_insurance_transfer_form_user FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE INDEX idx_insurance_transfer_form_user_id ON insurance_transfer_form (user_id);
