CREATE TABLE tax_data_consent
(
    id                        bigint GENERATED BY DEFAULT AS IDENTITY,
    user_id                   bigint      NOT NULL,
    status                    text        NOT NULL,
    consent_confirm_reference text,
    consent_document          bytea,
    signed_container          bytea,
    consent_reference         text,
    refreshed_at              timestamptz,
    lease_until               timestamptz,
    created_at                timestamptz NOT NULL,
    CONSTRAINT tax_data_consent_pkey PRIMARY KEY (id),
    CONSTRAINT uq_tax_data_consent_user_id UNIQUE (user_id),
    CONSTRAINT fk_tax_data_consent_user FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE TABLE tax_income_month
(
    id                     bigint GENERATED BY DEFAULT AS IDENTITY,
    user_id                bigint         NOT NULL,
    income_month           date           NOT NULL,
    income                 numeric(19, 2) NOT NULL,
    withheld_contributions numeric(19, 2) NOT NULL,
    CONSTRAINT tax_income_month_pkey PRIMARY KEY (id),
    CONSTRAINT uq_tax_income_month_user_id_income_month UNIQUE (user_id, income_month),
    CONSTRAINT fk_tax_income_month_user FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE TABLE tax_income_correction
(
    id           bigint GENERATED BY DEFAULT AS IDENTITY,
    user_id      bigint         NOT NULL,
    income_month date           NOT NULL,
    amount       numeric(19, 2) NOT NULL,
    CONSTRAINT tax_income_correction_pkey PRIMARY KEY (id),
    CONSTRAINT uq_tax_income_correction_user_id_income_month UNIQUE (user_id, income_month),
    CONSTRAINT fk_tax_income_correction_user FOREIGN KEY (user_id) REFERENCES users (id)
);
