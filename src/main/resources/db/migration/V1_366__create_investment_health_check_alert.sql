CREATE TABLE investment_health_check_alert (
    id          bigint GENERATED BY DEFAULT AS IDENTITY,
    provider    text        NOT NULL,
    report_date date        NOT NULL,
    message     text        NOT NULL,
    found_at    timestamptz NOT NULL,
    status      text        NOT NULL,
    posted_at   timestamptz,
    unanswered_posts integer NOT NULL,

    CONSTRAINT investment_health_check_alert_pkey PRIMARY KEY (id),
    CONSTRAINT investment_health_check_alert_status
        CHECK (status IN ('NOT_POSTED', 'POSTED', 'GIVEN_UP')),
    CONSTRAINT investment_health_check_alert_posted_carries_its_time
        CHECK ((status = 'POSTED') = (posted_at IS NOT NULL))
);

CREATE INDEX idx_health_check_alert_status_found_at
    ON investment_health_check_alert (status, found_at);
